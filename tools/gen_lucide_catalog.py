#!/usr/bin/env python3
"""
Generate the Lucide icon catalog used by the app.

Inputs
  --aar   path to the icons-lucide-android AAR the app depends on (source of truth for which icons exist)
  --repo  path to an extracted lucide-icons/lucide repository (for tags, categories and aliases)

Outputs
  app/src/main/java/com/idanariav/timetracker/ui/LucideCatalog.kt   name -> ImageVector lookup (every icon in the AAR)
  app/src/main/assets/lucide_icons.tsv                               search metadata (categories, tags) per icon

Re-run after upgrading the icons library:
  python3 tools/gen_lucide_catalog.py --aar <aar> --repo <lucide-main>
"""
import argparse
import io
import json
import pathlib
import re
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
KT_OUT = ROOT / "app/src/main/java/com/idanariav/timetracker/ui/LucideCatalog.kt"
TSV_OUT = ROOT / "app/src/main/assets/lucide_icons.tsv"
CHUNK = 250  # keeps each generated `when` well under the JVM method-size limit


def pascal(kebab: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in kebab.split("-"))


def aar_icon_names(aar: pathlib.Path) -> list[str]:
    with zipfile.ZipFile(aar) as z:
        jar = zipfile.ZipFile(io.BytesIO(z.read("classes.jar")))
    names = []
    for n in jar.namelist():
        m = re.fullmatch(r"com/composables/icons/lucide/(\w+)Kt\.class", n)
        # Icon files define an extension property `Lucide.<Name>` (getter `get<Name>`); skip helpers like LucideIconKt.
        if m and f"get{m.group(1)}".encode() in jar.read(n):
            names.append(m.group(1))
    return sorted(set(names))


def repo_meta(repo: pathlib.Path) -> tuple[dict, dict]:
    """PascalName -> (categories, tags); plus category id -> title."""
    meta = {}
    for f in sorted((repo / "icons").glob("*.json")):
        d = json.loads(f.read_text())
        entry = (d.get("categories", []), d.get("tags", []))
        meta[pascal(f.stem)] = entry
        # Old names (renamed icons) still exist in older libraries.
        for alias in d.get("aliases", []):
            name = alias["name"] if isinstance(alias, dict) else alias
            meta.setdefault(pascal(name), entry)
    cats = {f.stem: json.loads(f.read_text()).get("title", f.stem) for f in sorted((repo / "categories").glob("*.json"))}
    return meta, cats


def clean(words) -> str:
    return ",".join(sorted({w.strip().lower().replace("\t", " ").replace(",", " ") for w in words if w.strip()}))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--aar", required=True, type=pathlib.Path)
    ap.add_argument("--repo", required=True, type=pathlib.Path)
    args = ap.parse_args()

    names = aar_icon_names(args.aar)
    meta, cats = repo_meta(args.repo)

    # ---- TSV: "#cat<TAB>id<TAB>Title" header lines, then "Name<TAB>categories<TAB>tags"
    TSV_OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"#cat\t{cid}\t{title}" for cid, title in cats.items()]
    covered = 0
    for n in names:
        c, t = meta.get(n, ([], []))
        covered += n in meta
        lines.append(f"{n}\t{clean(c)}\t{clean(t)}")
    TSV_OUT.write_text("\n".join(lines) + "\n")

    # ---- Kotlin lookup
    chunks = [names[i:i + CHUNK] for i in range(0, len(names), CHUNK)]
    out = [
        "// GENERATED by tools/gen_lucide_catalog.py — do not edit by hand.",
        "@file:Suppress(\"LongMethod\", \"CyclomaticComplexMethod\")",
        "",
        "package com.idanariav.timetracker.ui",
        "",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import com.composables.icons.lucide.*",
        "",
        f"/** Every icon in the Lucide library ({len(names)}), looked up by its PascalCase name. */",
        "object LucideCatalog {",
        f"    const val COUNT = {len(names)}",
        "",
        "    fun icon(name: String): ImageVector? =",
        "        " + " ?: ".join(f"chunk{i}(name)" for i in range(len(chunks))),
    ]
    for i, chunk in enumerate(chunks):
        out += ["", f"    private fun chunk{i}(n: String): ImageVector? = when (n) {{"]
        out += [f"        \"{n}\" -> Lucide.{n}" for n in chunk]
        out += ["        else -> null", "    }"]
    out += ["}", ""]
    KT_OUT.write_text("\n".join(out))
    print(f"{len(names)} icons, {covered} with tags/categories, {len(cats)} categories")
    print(f"wrote {KT_OUT.relative_to(ROOT)} and {TSV_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
